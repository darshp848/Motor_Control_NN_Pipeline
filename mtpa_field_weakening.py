def mtpa_for_torque(T_ref, surrogate, n_pp, i_max, grid_n=400,
                    n_local=20):
    """For a given target torque T_ref, find (Id, Iq) that uses minimum
    stator current magnitude. Two-phase search:
      1. Dense uniform grid over |I_s| disk + torque constraint surface
      2. fine local refinement around best grid point

    Constraint: T(Id, Iq) = T_ref (== approx) AND |I_s| <= i_max.
    Objective: minimize |I_s| = sqrt(Id^2 + Iq^2).
    """
    # Search window. MTPA is conventionally in [-i_max, 0] for Id (FW side)
    # and [0, i_max] for Iq. Mirror for negative T_ref.
    sign = 1.0 if T_ref >= 0 else -1.0
    i_max_a = float(i_max)

    # Grid over the upper half-disk (Iq >= 0); flip sign at the end.
    id_grid = np.linspace(-i_max_a, 0.0, grid_n)
    iq_grid = np.linspace(0.0, i_max_a, grid_n)
    II, QQ = np.meshgrid(id_grid, iq_grid, indexing="ij")
    pts = np.stack([II.ravel(), QQ.ravel()], axis=1)
    T_arr, _ = surrogate.torque(pts, n_pp)
    diff = T_arr - T_ref
    mask = (np.abs(diff) < 0.05 * max(abs(T_ref), 1e-3)) & (np.sqrt(pts[:,0]**2 + pts[:,1]**2) <= i_max_a * 1.001)
    if not np.any(mask):
        # Looser tolerance
        mask = (np.abs(diff) < 0.20 * max(abs(T_ref), 1e-3)) & (np.sqrt(pts[:,0]**2 + pts[:,1]**2) <= i_max_a * 1.001)
    if not np.any(mask):
        return None
    cand = pts[mask]
    Is = np.sqrt(cand[:,0]**2 + cand[:,1]**2)
    best = int(np.argmin(Is))
    x_best = cand[best].copy()
    # Local search around x_best (coordinate-descent-style).
    step = 0.02 * i_max_a
    T_tol = 0.005 * max(abs(T_ref), 1e-3)
    for _ in range(n_local):
        for dim in (0, 1):
            for d in (+step, -step):
                cand_x = x_best.copy()
                cand_x[dim] += d
                if math.hypot(cand_x[0], cand_x[1]) > i_max_a * 1.0001:
                    continue
                T_j, _ = surrogate.torque(cand_x[None, :], n_pp)
                if abs(T_j[0] - T_ref) < T_tol or abs(T_j[0] - T_ref) < abs(surrogate.torque(x_best[None, :], n_pp)[0][0] - T_ref):
                    cand_j_norm = math.hypot(cand_x[0], cand_x[1])
                    best_norm = math.hypot(x_best[0], x_best[1])
                    if cand_j_norm < best_norm + 1e-9:
                        x_best = cand_x
        step *= 0.8
    return float(x_best[0]) * sign, float(x_best[1]) * sign, float(math.hypot(x_best[0], x_best[1]))


def mtpa_curve(surrogate, n_pp, i_max, t_refs, grid_n=400):
    """Returns list of (T_ref, Id, Iq, |I_s|)."""
    out = []
    for t in t_refs:
        r = mtpa_for_torque(t, surrogate, n_pp, i_max, grid_n=grid_n)
        if r is None:
            out.append((t, float("nan"), float("nan"), float("nan")))
        else:
            out.append((t, r[0], r[1], r[2]))
    return out


def fw_envelope(surrogate, n_pp, R_s, V_max, i_max, rpms):
    """For each mechanical speed (rpm), find the maximum torque subject to
    BOTH the current limit |Is| <= i_max AND the voltage limit |V| <= V_max.

    Strategy: brute force candidate generation over a fine grid in the dq
    plane, filter by both constraints, take the max achievable |T|.
    """
    out = []
    i_max_a = float(i_max)
    id_grid = np.linspace(-i_max_a, 0.0, 160)
    iq_grid = np.linspace(0.0, i_max_a, 160)
    II, QQ = np.meshgrid(id_grid, iq_grid, indexing="ij")
    pts = np.stack([II.ravel(), QQ.ravel()], axis=1)
    Is_all = np.sqrt(pts[:, 0] ** 2 + pts[:, 1] ** 2)
    cur_mask = Is_all <= i_max_a * 1.001
    # One batched flux eval for the whole dq grid (reused for T and all V(rpm)).
    T_all, Y_all = surrogate.torque(pts, n_pp)
    for rpm in rpms:
        omega_e = rpm_mech_to_we(float(rpm), n_pp)
        V_all, _, _ = surrogate.voltage(pts, omega_e, R_s, Y=Y_all)
        mask = cur_mask & (V_all <= V_max * 1.001)
        if not np.any(mask):
            out.append((float(rpm), float("nan"), float("nan"),
                        float("nan"), float("nan"), float("nan")))
            continue
        # Take the candidate with largest |T| at positive torque (motoring).
        idx = int(np.argmax(T_all[mask]))
        sel_pts = pts[mask]
        sel_T = T_all[mask]
        sel_V = V_all[mask]
        sel_Is = Is_all[mask]
        chosen = sel_pts[idx]
        out.append((float(rpm), float(sel_T[idx]), float(chosen[0]),
                    float(chosen[1]), float(sel_Is[idx]), float(sel_V[idx])))
    return out


def reference_lookup(surrogate, n_pp, R_s, V_max, i_max,
                     t_refs, rpms, grid_n=400, mtpa=None, env=None):
    """For each (rpm, T_ref), solve for min-|Is| feasible (Id, Iq).

    Same Id/Iq resolution as MTPA (default grid_n=400 half-disk), but one
    batched flux eval per rpm instead of nested micro-batches (which thrash
    sklearn RandomForest call overhead).

    If T_ref exceeds the FW envelope max at that rpm, mark infeasible and
    write the envelope-limited operating point instead.
    """
    if env is None:
        env = fw_envelope(surrogate, n_pp, R_s, V_max, i_max, rpms)
    if mtpa is None:
        mtpa = mtpa_curve(surrogate, n_pp, i_max, t_refs, grid_n=grid_n)
    env_dict = {row[0]: row for row in env}
    mtpa_dict = {row[0]: (row[1], row[2], row[3]) for row in mtpa}

    i_max_a = float(i_max)
    id_grid = np.linspace(-i_max_a, 0.0, grid_n)
    iq_grid = np.linspace(0.0, i_max_a, grid_n)
    II, QQ = np.meshgrid(id_grid, iq_grid, indexing="ij")
    pts = np.stack([II.ravel(), QQ.ravel()], axis=1)
    Is_all = np.sqrt(pts[:, 0] ** 2 + pts[:, 1] ** 2)
    cur_mask = Is_all <= i_max_a * 1.001

    # Flux/torque independent of speed — evaluate once for the whole grid.
    T_all, Y_all = surrogate.torque(pts, n_pp)

    rows = []
    for rpm in rpms:
        omega_e = rpm_mech_to_we(float(rpm), n_pp)
        V_all, _, _ = surrogate.voltage(pts, omega_e, R_s, Y=Y_all)
        volt_mask = V_all <= V_max * 1.001
        env_row = env_dict[rpm]
        T_max_fw = env_row[1] if not math.isnan(env_row[1]) else 0.0
        env_id, env_iq = env_row[2], env_row[3]

        for t in t_refs:
            if math.isnan(T_max_fw) or t > T_max_fw + 1e-6:
                rows.append((float(rpm), float(t), env_id, env_iq,
                             float("nan"), "infeasible"))
                continue
            mtpa_id, mtpa_iq, mtpa_norm = mtpa_dict[t]
            if math.isnan(mtpa_id):
                rows.append((float(rpm), float(t), float("nan"), float("nan"),
                             float("nan"), "mtpa_unavailable"))
                continue
            # MTPA point voltage check (single-row batch).
            X_try = np.array([[mtpa_id, mtpa_iq]])
            V_try, _, _ = surrogate.voltage(X_try, omega_e, R_s)
            if V_try[0] <= V_max * 1.001:
                rows.append((float(rpm), float(t), float(mtpa_id),
                             float(mtpa_iq), float(mtpa_norm), "mtpa"))
                continue
            # Voltage-limited: min |Is| on full-resolution grid with
            # |T - T_ref| tolerance and |V|<=V_max (same half-disk as MTPA).
            T_tol = 0.05 * max(abs(t), 1e-3)
            mask = (
                cur_mask & volt_mask
                & (np.abs(T_all - t) < T_tol)
            )
            if not np.any(mask):
                T_tol = 0.20 * max(abs(t), 1e-3)
                mask = (
                    cur_mask & volt_mask
                    & (np.abs(T_all - t) < T_tol)
                )
            if not np.any(mask):
                rows.append((float(rpm), float(t), float("nan"), float("nan"),
                             float("nan"), "fw_search_failed"))
                continue
            sub = np.where(mask)[0]
            k = sub[int(np.argmin(Is_all[sub]))]
            rows.append((
                float(rpm), float(t),
                float(pts[k, 0]), float(pts[k, 1]),
                float(Is_all[k]), "fw",
            ))
    return rows, env


