def overlay_params_from_json(ns):
    if ns.no_use_params_json:
        return
    p = ns.params_json
    if not p or not os.path.exists(p):
        return
    try:
        with open(p, "r") as f:
            j = json.load(f)
    except Exception:
        return
    def copy_if(key, attr, cast):
        if key in j and j[key] is not None:
            try:
                setattr(ns, attr, cast(j[key]))
                print(f"[params-json] overriding {attr} = {j[key]}")
            except Exception:
                pass
    copy_if("poles", "poles", int)
    copy_if("pole_pairs", "poles", lambda v: int(v*2))  # tolerate pole_pairs
    copy_if("rs_ohm", "rs", float)
    copy_if("vdc_v", "vdc", float)
    copy_if("i_max_peak_a", "i_max_peak", float)
    copy_if("i_rated_peak_a", "i_rated_peak", float)
    copy_if("t_rated_nm", "t_rated", float)
    copy_if("flux_scale", "flux_scale", float)
    copy_if("flux_scale", "flux_scale", float)
    copy_if("omega_mech_base_rpm", "omega_mech_base_rpm", float)
    copy_if("omega_mech_max_rpm", "omega_mech_max_rpm", float)


def write_csv(path, header, rows, fmt_row=None):
    import csv
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        for r in rows:
            if fmt_row:
                w.writerow(fmt_row(r))
            else:
                w.writerow(r)


def main():
    ns = parse_args()
    overlay_params_from_json(ns)

    os.makedirs(ns.out, exist_ok=True)

    inf, inf_path = _load_surrogate()
    print(f"[load] inference module: {inf_path}")

    surrogate = FluxSurrogate(inf, flux_scale=ns.flux_scale)

    # V_max via SVPWM: max |V_dq| per phase (peak) = vdc / sqrt(3).
    V_max = ns.vdc / math.sqrt(3.0)
    # Account for inverter drop optionally absorbed in vdc; user adjusts if needed.
    print(f"[params] poles={ns.poles}, pp={ns.poles//2}, rs={ns.rs:.4f} ohm, "
          f"V_dc={ns.vdc:.1f} V -> V_max_phase_peak(SVPWM)={V_max:.3f} V")
    print(f"[params] i_max_peak={ns.i_max_peak} A, "
          f"omega_base={ns.omega_mech_base_rpm} rpm, "
          f"omega_max={ns.omega_mech_max_rpm} rpm, "
          f"flux_scale={ns.flux_scale:.4g}")

    torque_sanity(surrogate, ns.poles // 2, ns.i_rated_peak, ns.t_rated,
                  ns.out)

    # Save params.
    with open(os.path.join(ns.out, "motor_params_used.json"), "w") as f:
        json.dump({
            "poles": int(ns.poles),
            "pole_pairs": int(ns.poles // 2),
            "rs_ohm": ns.rs,
            "vdc_v": ns.vdc,
            "vmax_phase_peak_v": V_max,
            "i_max_peak_a": ns.i_max_peak,
            "i_rated_peak_a": ns.i_rated_peak,
            "t_rated_nm": ns.t_rated,
            "flux_scale": ns.flux_scale,
            "omega_mech_base_rpm": ns.omega_mech_base_rpm,
            "omega_mech_max_rpm": ns.omega_mech_max_rpm,
            "inference_path": inf_path,
        }, f, indent=2)

    # MTPA curve (400x400 Id-Iq half-disk per torque sample; batched RF).
    print("\n[mtpa] computing MTPA curve over %d torque samples (grid_n=400)..."
          % ns.n_t_ref)
    t_refs = np.linspace(0.0, ns.t_ref_max, ns.n_t_ref).tolist()
    mtpa = mtpa_curve(surrogate, ns.poles // 2, ns.i_max_peak, t_refs,
                      grid_n=400)
    write_csv(os.path.join(ns.out, "mtpa_curve.csv"),
              ["T_ref_Nm", "Id_A", "Iq_A", "Is_norm_A"],
              mtpa,
              fmt_row=lambda r: [("%.6f" % r[0]), ("%.6f" % r[1]),
                                  ("%.6f" % r[2]), ("%.6f" % r[3])])
    print(f"[mtpa] wrote {os.path.join(ns.out, 'mtpa_curve.csv')}")

    # FW envelope.
    print("\n[fw] computing torque-speed envelope over %d rpm samples..."
          % ns.n_rpm)
    rpms = np.linspace(0.0, ns.omega_mech_max_rpm, ns.n_rpm).tolist()
    env = fw_envelope(surrogate, ns.poles // 2, ns.rs, V_max,
                      ns.i_max_peak, rpms)
    write_csv(os.path.join(ns.out, "fw_envelope.csv"),
              ["rpm", "T_max_fw_Nm", "Id_A", "Iq_A", "Is_norm_A", "V_norm_V"],
              env,
              fmt_row=lambda r: [("%.6f" % r[0]), ("%.6f" % r[1]),
                                  ("%.6f" % r[2]), ("%.6f" % r[3]),
                                  ("%.6f" % r[4]), ("%.6f" % r[5])])
    print(f"[fw] wrote {os.path.join(ns.out, 'fw_envelope.csv')}")

    # Reference LUT — reuse mtpa/env; full-res 400x400 batch per rpm.
    print("\n[ref] computing full reference look-up (rpm x T_ref), "
          "grid_n=400 batched...")
    lookup, _ = reference_lookup(
        surrogate, ns.poles // 2, ns.rs, V_max,
        ns.i_max_peak, t_refs, rpms,
        grid_n=400, mtpa=mtpa, env=env,
    )
    write_csv(os.path.join(ns.out, "reference_lookup.csv"),
              ["rpm_mech", "T_ref_Nm", "Id_ref_A", "Iq_ref_A", "Is_norm_A", "status"],
              lookup,
              fmt_row=lambda r: [("%.6f" % r[0]), ("%.6f" % r[1]),
                                  ("%.6f" % r[2]), ("%.6f" % r[3]),
                                  ("%.6f" % r[4]), str(r[5])])
    print(f"[ref] wrote {os.path.join(ns.out, 'reference_lookup.csv')}")

    # Plot.
    plot_overview(surrogate, ns.poles // 2, ns.i_max_peak, mtpa, env, lookup,
                  ns.out)
    print(f"\n[done] outputs under {ns.out}")
    print("Next: feed reference_lookup.csv into the motor-controller LUT, OR "
          "run pull_motor_params.py (AEDT) to verify --flux-scale and "
          "poles/vdc before locking the LUT in.")


if __name__ == "__main__":
    main()