def plot_overview(surrogate, n_pp, i_max, mtpa, env, lookup, out_dir):
    if not _HAS_MPL:
        return
    fig, axes = plt.subplots(2, 2, figsize=(14, 11))

    # (0, 0) Phi_d(Id, Iq)
    id_grid = np.linspace(-i_max, 0, 80)
    iq_grid = np.linspace(0, i_max, 80)
    II, QQ = np.meshgrid(id_grid, iq_grid, indexing="ij")
    pts = np.stack([II.ravel(), QQ.ravel()], axis=1)
    Ph = surrogate.predict(pts)
    PD = Ph[:, 0].reshape(II.shape)
    PQ = Ph[:, 1].reshape(II.shape)
    ax = axes[0][0]
    cs = ax.contourf(II, QQ, PD, levels=24, cmap="viridis")
    fig.colorbar(cs, ax=ax, label="Phi_d (Wb)")
    ax.set_xlabel("Id (A)"); ax.set_ylabel("Iq (A)")
    ax.set_title("Surrogate Phi_d(Id, Iq)")

    # (0, 1) Torque map + MTPA curve
    T_arr, _ = surrogate.torque(pts, n_pp)
    T_map = T_arr.reshape(II.shape)
    ax = axes[0][1]
    cs = ax.contourf(II, QQ, T_map, levels=24, cmap="RdBu_r")
    ax.contour(II, QQ, T_map, levels=12, colors="k", linewidths=0.3)
    fig.colorbar(cs, ax=ax, label="T (N.m)")
    if mtpa:
        ids = [r[1] for r in mtpa if not math.isnan(r[1])]
        iqs = [r[2] for r in mtpa if not math.isnan(r[2])]
        ax.plot(ids, iqs, "o-", color="black", ms=3, label="MTPA")
        ax.legend(loc="upper right", fontsize=8)
    ax.set_xlabel("Id (A)"); ax.set_ylabel("Iq (A)")
    ax.set_title("Isotorque contours + MTPA")

    # (1, 0) T-rpm envelope
    ax = axes[1][0]
    rpms_arr = np.array([r[0] for r in env], dtype=np.float64)
    T_max_arr = np.array([r[1] for r in env], dtype=np.float64)
    ax.plot(rpms_arr, T_max_arr, "-", color="C0", label="T_max (FW envelope)")
    ax.set_xlabel("mech rpm"); ax.set_ylabel("T_max (N.m)")
    ax.set_title("Torque-speed envelope under I and V limits")
    ax.legend(fontsize=9)

    # (1, 1) Reference LUT (rows end with a status string — do not cast all cols)
    ax = axes[1][1]
    meas = []
    for row in lookup:
        try:
            id_ref = float(row[2])
            iq_ref = float(row[3])
        except (TypeError, ValueError):
            continue
        if math.isnan(id_ref) or math.isnan(iq_ref):
            continue
        if str(row[5]) in ("infeasible", "mtpa_unavailable", "fw_search_failed"):
            continue
        meas.append((float(row[0]), float(row[1]), id_ref, iq_ref))
    if len(meas) >= 3:
        arr = np.array(meas, dtype=np.float64)
        rpms_uniq = np.unique(arr[:, 0])
        for r in rpms_uniq[:: max(1, int(len(rpms_uniq) / 8))]:
            sel = arr[arr[:, 0] == r]
            ax.plot(sel[:, 1], sel[:, 3], "o-", ms=3,
                    label="%.0f rpm" % r)
    ax.set_xlabel("T_ref (N.m)"); ax.set_ylabel("Iq_ref (A)")
    ax.set_title("Reference LUT (Iq_ref vs T_ref at selected speeds)")
    ax.legend(fontsize=7, loc="best")

    plt.tight_layout()
    plt.savefig(os.path.join(out_dir, "mtpa_fw_overview.png"), dpi=140)
    plt.close(fig)


