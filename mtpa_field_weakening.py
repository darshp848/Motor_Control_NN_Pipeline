def torque_sanity(surrogate, n_pp, i_rated_peak, t_rated, out_dir):
    """At (Id, Iq) = (0, I_rated_peak) the implied torque should be in the
    right neighborhood of T_rated. If wildly off, print a suggested
    --flux-scale to fix it. (0, Iq) is the pure-PM-torque operating point;
    real MTPA for IPMs uses Id < 0, but (0, rated) is a stable enough probe
    to detect a flux units mismatch."""
    X = np.array([[0.0, float(i_rated_peak)]])
    T_pred, Y_pred = surrogate.torque(X, n_pp)
    T_pred_val = float(T_pred[0])
    scale_factor = t_rated / T_pred_val if abs(T_pred_val) > 1e-9 else float("nan")
    lines = []
    lines.append("Torque sanity check")
    lines.append("  Point explored: Id=0, Iq=I_rated_peak=%.4f A" % i_rated_peak)
    lines.append("  Surrogate Phi_d=%.6e Wb, Phi_q=%.6e Wb" % (Y_pred[0, 0], Y_pred[0, 1]))
    lines.append("  Implied rated torque T = %.6e N.m" % T_pred_val)
    lines.append("  Expected rated torque T = %.6e N.m (from RMxprt 0.res)" % t_rated)
    if math.isfinite(scale_factor) and (scale_factor < 0.1 or scale_factor > 10.0):
        lines.append("  >>> OFF by factor %.3f - flux linkage units mismatch. Suggested re-run:" % scale_factor)
        lines.append("  >>> python mtpa_field_weakening.py --flux-scale %.6g"
                     % scale_factor)
    elif abs(scale_factor - 1.0) < 0.05:
        lines.append("  OK - implied torque within 5% of rated.")
    else:
        lines.append("  WARNING: implied torque within %.1f%% of rated; check results carefully."
                     % (100.0 * abs(scale_factor - 1.0)))
    log = "\n".join(lines) + "\n"
    print(log)
    with open(os.path.join(out_dir, "torque_sanity.log"), "w") as f:
        f.write(log)


