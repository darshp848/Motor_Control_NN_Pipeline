class FluxSurrogate:
    def __init__(self, inf_module, flux_scale=1.0):
        self._predict = inf_module.predict
        # Prefer batched path (sklearn RF / numpy models); fall back to scalar loop.
        self._predict_batch = getattr(inf_module, "predict_batch", None)
        self.flux_scale = float(flux_scale)

    def predict(self, X):
        """X: (n, 2) array of [Id, Iq].  Returns (n, 2) array of [Phi_d, Phi_q]."""
        X = np.asarray(X, dtype=np.float64)
        if X.ndim == 1:
            X = X.reshape(1, -1)
        n = X.shape[0]
        if self._predict_batch is not None:
            Y = np.asarray(self._predict_batch(X), dtype=np.float64)
            if Y.ndim == 1:
                Y = Y.reshape(-1, 2)
            return Y * self.flux_scale
        # Scalar fallback (slow): one model call per row.
        out = np.empty((n, 2), dtype=np.float64)
        for i in range(n):
            pd, pq = self._predict(float(X[i, 0]), float(X[i, 1]))
            out[i, 0] = pd * self.flux_scale
            out[i, 1] = pq * self.flux_scale
        return out

    def torque(self, X, n_pp):
        """IPM torque for each row of X.

        T = (3/2) * P * (Phi_d * Iq - Phi_q * Id)
        """
        Y = self.predict(X)
        T = 1.5 * n_pp * (Y[:, 0] * X[:, 1] - Y[:, 1] * X[:, 0])
        return T, Y

    def voltage(self, X, omega_e, R_s, Y=None):
        """Stator dq-frame voltage magnitudes.
        V_d = R_s * Id - omega_e * Phi_q
        V_q = R_s * Iq + omega_e * Phi_d
        (motor convention, omega_e = electrical angular vel rad/s)

        Optional Y: precomputed flux (n,2) to avoid a second model call.
        """
        if Y is None:
            Y = self.predict(X)
        Vd = R_s * X[:, 0] - omega_e * Y[:, 1]
        Vq = R_s * X[:, 1] + omega_e * Y[:, 0]
        return np.sqrt(Vd * Vd + Vq * Vq), Vd, Vq


