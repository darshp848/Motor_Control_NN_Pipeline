"""MTPA + field-weakening reference lookup from the validated flux surrogate.

Reads:
    inference_flux_map.py   (auto-generated by train_flux_map_comparison.py)
        -> exposes predict(Id, Iq) -> (Phi_d, Phi_q)
    (optional) motor_params.json          (written by pull_motor_params.py
                                           running in AEDT; if absent, falls
                                           back to CLI args / defaults)

Computes operating-envelope characterization for an IPM motor:
  T(Id, Iq) = (3/2) * P * (Phi_d(Id,Iq) * Iq - Phi_q(Id,Iq) * Id)

Outputs (under out/mtpa/):
  - motor_params_used.json              - the parameters actually used
  - mtpa_curve.csv                      - (T_ref, Id_mtpa, Iq_mtpa, |I_s|)
  - fw_envelope.csv                     - (rpm, T_max_fw, Id_fw, Iq_fw, |I_s|, |V|)
  - reference_lookup.csv                - dense (rpm, T_ref) -> (Id_ref, Iq_ref)
                                          grid for the controller's LUT
  - mtpa_fw_overview.png                - 4-panel plot:
                                          (1) flux map Phi_d(Id, Iq)
                                          (2) T(Id, Iq) isotorque contours
                                              + MTPA curve overlay
                                          (3) T-rpm envelope with limited
                                              current and voltage circles
                                          (4) Id_ref/Iq_ref reference LUT
  - torque_sanity.log                   - rated point check (implied rated
                                          torque from surrogate vs. expected)

The script prints a rated-torque sanity check at startup. If the implied
rated torque is off from the expected value (default 2.89531 N.m, taken
from RMxprt 0.res), it prints the flux scale factor that would fix it;
re-run with --flux-scale <that_value>.

CLI args:
  --poles               default 4 (number of poles; pole pairs = poles/2)
  --rs                  default 2.15938 (per-phase stator resistance, ohm)
  --vdc                 default 311  (DC bus voltage, V; sqrt(2)*220)
  --omega-mech-max-rpm  default 6000  (max mechanical speed, rpm)
  --omega-mech-base-rpm default 1800  (base / synchronous speed, rpm)
  --i-max-peak          default 6.0  (peak stator current amplitude, A)
  --t-ref-max           default 4.0  (upper torque sweep bound, N.m)
  --n-t-ref             default 50  (MTPA Torque samples)
  --n-rpm               default 60  (FW speed samples)
  --flux-scale          default 1.0  (multiplier to convert FEM flux linkage
                                     to SI Wb-turns; see torque sanity)
  --models-dir          default out
  --out                 default out/mtpa
  --params-json         optional path to motor_params.json (from pull_motor_params.py);
                        if present, overrides the CLI defaults with values
                        found there; CLI args still take priority via
                        --no-use-params-json


Usage:
    .venv\\Scripts\\python mtpa_field_weakening.py \\
        --params-json out/motor_params.json
"""

